export function getLanguage() {
  if (typeof localStorage === 'undefined') return 'es';
  return localStorage.getItem('bottlecrm-language') || 'es';
}

export function setLanguage(language) {
  if (typeof localStorage !== 'undefined') localStorage.setItem('bottlecrm-language', language);
  if (typeof window !== 'undefined') window.dispatchEvent(new CustomEvent('bottlecrm-language', { detail: language }));
}

export function tr(language, key) {
  return translations[language]?.[key] || translations.es[key] || key;
}
